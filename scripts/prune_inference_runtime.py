#!/usr/bin/env python3
"""Build/verify an explicitly derived compact VSE runtime, never rewrite wheels/RECORD.

Default is a dry run. Use --apply --manifest PATH after offline installation.
Run supported launchers with PYTHONDONTWRITEBYTECODE=1 and install --no-compile.
The optional OpenVINO plugin omission supports engine=paddle ONLY, Linux x86_64
Paddle 3.3.1; the hard-linked OpenVINO core/MKL/oneDNN libraries are never removed.
"""
import argparse
import base64
import csv
import hashlib
import importlib.metadata
import json
import os
import platform
from pathlib import Path
import sysconfig

# Package tests actually covered by the compact Linux full-suite/E2E experiment.
TEST_ROOTS = {
    'aistudio_sdk', 'certifi', 'fsspec', 'future', 'modelscope', 'networkx',
    'numpy', 'opt_einsum', 'pandas', 'pkg_resources', 'setuptools', 'shapely',
}
TEST_VERSIONS = {
    'aistudio_sdk': ('aistudio-sdk', '0.3.9'), 'certifi': ('certifi', '2026.10.23'),
    'fsspec': ('fsspec', '2026.9.0'), 'future': ('future', '1.0.0'),
    'modelscope': ('modelscope', '1.40.2'), 'networkx': ('networkx', '3.7'),
    'numpy': ('numpy', '2.3.5'), 'opt_einsum': ('opt-einsum', '3.3.0'),
    'pandas': ('pandas', '3.1.0'), 'pkg_resources': ('setuptools', '80.10.2'),
    'setuptools': ('setuptools', '80.10.2'), 'shapely': ('shapely', '2.2.0'),
}
PLUGIN = 'paddle/libs/libopenvino_intel_cpu_plugin.so'


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def normalized(name):
    return name.lower().replace('_', '-').replace('.', '-')


def installed(root):
    versions = {}
    records = {}
    for dist in importlib.metadata.distributions(path=[str(root)]):
        name = normalized(dist.metadata['Name'])
        versions[name] = dist.version
        record = dist.read_text('RECORD')
        if not record:
            continue
        for row in csv.reader(record.splitlines()):
            if len(row) != 3:
                raise ValueError(f'Invalid RECORD row in {name}')
            rel, hashed, size = row
            if hashed.startswith('sha256='):
                records[rel] = (hashed[7:], int(size), name)
    return versions, records


def reason_for(rel, versions, include_openvino=False):
    parts = Path(rel).parts
    if not parts:
        return None
    # Never discard attribution/license material, even nested in test trees.
    basename = parts[-1].lower()
    if not basename.endswith('.pyc') and basename.startswith(('license', 'licence', 'copying', 'notice', 'copyright', 'third_party', 'third-party', 'thirdparty')):
        return None
    if '__pycache__' in parts and basename.endswith('.pyc'):
        return 'generated bytecode cache; supported launchers disable regeneration'
    if parts[0] in TEST_ROOTS and ('tests' in parts or 'test' in parts):
        name, reviewed_version = TEST_VERSIONS[parts[0]]
        return 'third-party package test assets; validated VSE inference profile' if versions.get(name) == reviewed_version else None
    if len(parts) > 1 and parts[:2] == ('paddle', 'include'):
        return 'Paddle developer headers' if versions.get('paddlepaddle') == '3.3.1' else None
    if len(parts) > 1 and parts[:2] in (('PySide6', 'include'), ('PySide6', 'typesystems')):
        return 'PySide developer metadata' if versions.get('pyside6-essentials') == '6.12.0' else None
    qt_parts = parts[2:] if parts[:2] == ('PySide6', 'Qt') else parts[1:] if parts[0] == 'PySide6' else ()
    if qt_parts in (('lib', 'libQt6WaylandCompositor.so.6'), ('lib', 'libQt6WaylandEglCompositorHwIntegration.so.6')):
        return 'unused Wayland compositor/server libraries; desktop client support retained' if versions.get('pyside6-essentials') == '6.12.0' else None
    if qt_parts and qt_parts[0] == 'qml':
        return 'unused QML assets; VSE uses Qt Widgets, not Quick/QML' if versions.get('pyside6-essentials') == '6.12.0' else None
    if len(qt_parts) > 1 and qt_parts[0] == 'plugins':
        if qt_parts[1] == 'wayland-graphics-integration-server':
            return 'unused Wayland server plugins; desktop client plugins retained' if versions.get('pyside6-essentials') == '6.12.0' else None
        if qt_parts[1] in ('designer', 'qmltooling', 'sqldrivers', 'egldeviceintegrations'):
            return 'unused Qt Designer/QML tooling/SQL/embedded-EGLFS plugins' if versions.get('pyside6-essentials') == '6.12.0' else None
        if qt_parts[1] == 'platforms' and parts[-1] in ('libqeglfs.so', 'libqeglfs.dylib', 'qeglfs.dll'):
            return 'embedded full-screen EGLFS platform; desktop XCB/Wayland retained' if versions.get('pyside6-essentials') == '6.12.0' else None
        if qt_parts[1] == 'platforminputcontexts' and parts[-1] in ('libqtvirtualkeyboardplugin.so', 'libqtvirtualkeyboardplugin.dylib', 'qtvirtualkeyboardplugin.dll'):
            return 'unused virtual-keyboard plugin; native input methods retained' if versions.get('pyside6-essentials') == '6.12.0' else None
        if qt_parts[1] == 'imageformats' and parts[-1] in ('libqpdf.so', 'libqpdf.dylib', 'qpdf.dll'):
            return 'unused PDF image plugin; PDF runtime intentionally excluded' if versions.get('pyside6-essentials') == '6.12.0' else None
    if basename.endswith('.pyi'):
        return 'static type stubs; not executable runtime code'
    if include_openvino and rel == PLUGIN:
        return 'unused OpenVINO CPU plugin; VSE engine=paddle only'
    return None


def safe_files(root):
    for directory, dirs, names in os.walk(root, followlinks=False):
        for name in dirs + names:
            path = Path(directory) / name
            if path.is_symlink():
                raise ValueError(f'Symlink not supported in compact runtime: {path}')
        for name in names:
            path = Path(directory) / name
            if path.is_file():
                yield path


def file_record(path, root):
    return {'path': path.relative_to(root).as_posix(), 'size': path.stat().st_size,
            'sha256': digest(path)}


def build_plan(root, include_openvino=False, engine="paddle"):
    if engine not in ("paddle", "native", "directml") or (engine != "paddle" and include_openvino):
        raise ValueError("Invalid inference engine / OpenVINO pruning combination")
    versions, records = installed(root)
    if include_openvino and not (
        platform.system() == 'Linux' and platform.machine().lower() in ('x86_64', 'amd64')
        and versions.get('paddlepaddle') == '3.3.1'
    ):
        raise ValueError('OpenVINO plugin omission requires reviewed Linux x86_64 Paddle 3.3.1')
    removed, retained = [], []
    for path in sorted(safe_files(root)):
        entry = file_record(path, root)
        reason = reason_for(entry['path'], versions, include_openvino)
        if reason:
            # Non-cache vendor assets must exactly match official wheel RECORD.
            if not reason.startswith('generated bytecode'):
                recorded = records.get(entry['path'])
                hashed = base64.urlsafe_b64encode(bytes.fromhex(entry['sha256'])).decode().rstrip('=')
                if not recorded or recorded[:2] != (hashed, entry['size']):
                    raise ValueError(f'Unrecorded or changed candidate: {entry["path"]}')
                entry['distribution'] = recorded[2]
            entry['reason'] = reason
            removed.append(entry)
        else:
            retained.append(entry)
    return {'schema': 1, 'profile': 'VSE inference-only', 'engine': engine,
            'platform': {'system': platform.system(), 'machine': platform.machine()},
            'distributions': versions, 'original_RECORD_unchanged': True,
            'requires_no_bytecode_launcher': True,
            'removed': removed, 'retained': retained,
            'removed_bytes': sum(e['size'] for e in removed),
            'retained_bytes': sum(e['size'] for e in retained)}


def child_path(root, relative):
    rel = Path(relative)
    if rel.is_absolute() or '..' in rel.parts:
        raise ValueError(f'Unsafe manifest path: {relative}')
    path = root / rel
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'Manifest path escapes runtime: {relative}')
    return path


def verify(root, manifest):
    if manifest.get('schema') != 1 or manifest.get('engine') not in ('paddle', 'native', 'directml'):
        raise ValueError('Unsupported compact-runtime manifest')
    actual = {p.relative_to(root).as_posix(): p for p in safe_files(root)}
    retained = {e['path']: e for e in manifest['retained']}
    if set(actual) != set(retained):
        raise ValueError(f'Runtime file set changed: missing={sorted(set(retained)-set(actual))[:5]}, '
                         f'extra={sorted(set(actual)-set(retained))[:5]}')
    for rel, entry in retained.items():
        path = child_path(root, rel)
        if path.stat().st_size != entry['size'] or digest(path) != entry['sha256']:
            raise ValueError(f'Retained file changed: {rel}')
    for entry in manifest['removed']:
        if child_path(root, entry['path']).exists():
            raise ValueError(f'Pruned file regenerated: {entry["path"]}')
    return True



def resume_pending(root, manifest):
    """Finish an interrupted apply only after auditing every existing file.

    Strict --verify still rejects partial deletion; --apply can recover files
    listed as removed that still exactly match their original recorded bytes.
    """
    if manifest.get('schema') != 1 or manifest.get('engine') not in ('paddle', 'native', 'directml'):
        raise ValueError('Unsupported compact-runtime manifest')
    actual = {p.relative_to(root).as_posix(): p for p in safe_files(root)}
    retained = {e['path']: e for e in manifest['retained']}
    removed = {e['path']: e for e in manifest['removed']}
    if set(retained) & set(removed):
        raise ValueError('Overlapping retained/removed manifest paths')
    if set(retained) - set(actual) or set(actual) - (set(retained) | set(removed)):
        raise ValueError('Runtime file set changed; cannot resume pruning')
    # Validate all paths, including absent removed paths, against traversal.
    for rel in set(retained) | set(removed):
        child_path(root, rel)
    for rel, path in actual.items():
        entry = retained.get(rel, removed.get(rel))
        if path.stat().st_size != entry['size'] or digest(path) != entry['sha256']:
            raise ValueError(f'Runtime file changed; cannot resume pruning: {rel}')
    for rel in set(actual) & set(removed):
        actual[rel].unlink()
    verify(root, manifest)


def apply_plan(root, plan, manifest_path):
    if manifest_path.resolve().is_relative_to(root.resolve()):
        raise ValueError('Keep pruning manifest outside site-packages')
    previous = None
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text(encoding='utf-8'))
        verify(root, previous)
        if previous['distributions'] != plan['distributions'] or previous.get('engine') != plan.get('engine'):
            raise ValueError('Cannot extend manifest after vendor version or engine changes')
    # Validate everything before deleting anything; reject source changes after planning.
    for entry in plan['removed'] + plan['retained']:
        path = child_path(root, entry['path'])
        if path.is_symlink() or not path.is_file() or file_record(path, root) != {
            k: entry[k] for k in ('path', 'size', 'sha256')
        }:
            raise ValueError(f'Runtime changed after planning: {entry["path"]}')
    additions = list(plan['removed'])
    if previous:
        plan = dict(plan, removed=previous['removed'] + additions,
                    removed_bytes=previous['removed_bytes'] + plan['removed_bytes'])
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = manifest_path.with_name(manifest_path.name + '.tmp')
    temporary.write_text(json.dumps(plan, indent=2) + '\n', encoding='utf-8')
    temporary.replace(manifest_path)
    for entry in additions:
        child_path(root, entry['path']).unlink()
    verify(root, plan)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site-packages', type=Path, default=Path(sysconfig.get_path('purelib')))
    parser.add_argument('--manifest', type=Path, required=True)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--apply', action='store_true')
    modes.add_argument('--verify', action='store_true')
    parser.add_argument('--engine', choices=('paddle', 'native', 'directml'), default='paddle')
    parser.add_argument('--include-unused-openvino', action='store_true')
    args = parser.parse_args(argv)
    root = args.site_packages.resolve()
    if not root.is_dir():
        raise ValueError('site-packages directory does not exist')
    if args.verify:
        verify(root, json.loads(args.manifest.read_text(encoding='utf-8')))
        print('COMPACT_RUNTIME_VERIFIED')
        return 0
    if args.apply and args.manifest.exists():
        resume_pending(root, json.loads(args.manifest.read_text(encoding='utf-8')))
    plan = build_plan(root, args.include_unused_openvino, args.engine)
    if args.apply:
        apply_plan(root, plan, args.manifest)
    print(json.dumps({'applied': args.apply, 'removed_bytes': plan['removed_bytes'],
                      'retained_bytes': plan['retained_bytes'], 'removed_files': len(plan['removed'])}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
