"""Stage a verified native CPU worker without importing the inference frameworks.

The input inventory is generated by the native build job, not hand-authored from
filenames. Platform compiler runtimes are resolved by the existing native audits.
"""
from __future__ import annotations
import json
from pathlib import Path, PurePosixPath
import shutil

try:
    from .bundle_bootstrap import sha256
except ImportError:
    from bundle_bootstrap import sha256

FORBIDDEN_DISTRIBUTIONS = frozenset({
    'paddlepaddle', 'paddlepaddle-gpu', 'paddleocr', 'paddlex',
    'onnxruntime', 'onnxruntime-gpu', 'onnxruntime-directml',
    'torch', 'tensorflow', 'pyside6-addons',
})


def assert_native_requirements(requirements):
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name
    forbidden = FORBIDDEN_DISTRIBUTIONS.intersection(
        canonicalize_name(Requirement(value).name) for value in requirements)
    if forbidden:
        raise RuntimeError(f'Native GUI runtime contains forbidden inference stacks: {sorted(forbidden)}')


def safe_file(root, relative):
    path = PurePosixPath(relative)
    if not path.parts or path.is_absolute() or '..' in path.parts or '\\' in relative or ':' in relative or str(path) != relative:
        raise ValueError(f'Unsafe native artifact path: {relative}')
    candidate = root / relative
    if candidate.is_symlink() or not candidate.is_file() or not candidate.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'Invalid native artifact file: {relative}')
    return candidate


def stage_native_artifact(source: Path, destination: Path, platform: str) -> dict:
    """Copy only inventoried, hash-verified runtime files; materialize SONAME once."""
    source = source.resolve(strict=True)
    inventory = json.loads((source / 'size-audit.json').read_text(encoding='utf-8'))
    if (inventory.get('runner_test_only') or inventory.get('provenance', {}).get('runner_test_only')
            or (source / 'RUNNER-TEST-ONLY.json').exists()):
        raise ValueError('Runner-test-only artifact cannot become a customer package; redistribution rights pending')
    records = inventory['files']
    names = [record['path'] for record in records]
    if len(names) != len(set(names)):
        raise ValueError('Duplicate native inventory path')
    executable = 'native-ocr.exe' if platform == 'windows' else 'native-ocr'
    required = {executable, 'model-manifest.json', 'dependency-source-manifest.json', 'source_manifest.json'}
    if not required.issubset(names) or not any(name.startswith('licenses/') for name in names):
        raise ValueError('Native artifact lacks executable, model provenance or licenses')
    validated = {}
    for record in records:
        path = safe_file(source, record['path'])
        if path.stat().st_size != record['bytes'] or sha256(path) != record['sha256']:
            raise ValueError(f'Native inventory checksum mismatch: {record["path"]}')
        validated[record['path']] = path
    models = json.loads(validated['model-manifest.json'].read_text(encoding='utf-8'))
    if len(models) != 15 or len({row['name'] for row in models}) != 15:
        raise ValueError('Complete native profile requires all 15 distinct validated models')
    for row in models:
        model = f'models/{row["name"]}.onnx'
        config = row['config_file']
        if model not in validated or config not in validated:
            raise ValueError(f'Native model/config missing: {row["name"]}')
        if sha256(validated[model]) != row['onnx_sha256'] or sha256(validated[config]) != row['config_sha256']:
            raise ValueError(f'Native model/config checksum mismatch: {row["name"]}')
    destination.mkdir(parents=True, exist_ok=False)
    copied = {}
    for relative, path in validated.items():
        # Executable launcher/build reports are not part of the application.
        if relative == 'run.sh':
            continue
        target_relative = relative
        if platform == 'linux' and relative == 'libonnxruntime.so.1.31.0':
            target_relative = 'libonnxruntime.so.1'
        target = destination / target_relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        copied[target_relative] = sha256(target)
    return {'profile': 'native-cpu', 'model_count': 15, 'files': copied,
            'upstream_artifact_release_ready': inventory.get('release_ready', False),
            'note': 'Final platform native closure and clean-client verification remain mandatory.'}
